use std::time::Duration;

use sea_orm::{ConnectOptions, Database, DatabaseConnection, DbErr};

pub async fn open(path: &str) -> Result<DatabaseConnection, DbErr> {
    // sqlite://path/to/db.sqlite?mode=rwc;
    let path = format!("sqlite://{}?mode=rw", path);
    let mut opt = ConnectOptions::new(path);
    opt.max_connections(100)
        .min_connections(5)
        .connect_timeout(Duration::from_secs(8))
        .acquire_timeout(Duration::from_secs(8))
        .idle_timeout(Duration::from_secs(8))
        .max_lifetime(Duration::from_secs(8))
        .sqlx_logging(true)
        .sqlx_logging_level(log::LevelFilter::Error);
    let db = Database::connect(opt).await?;
    Ok(db)
}